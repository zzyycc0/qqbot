const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  getConfig: () => ipcRenderer.invoke('cfg:get'),
  saveConfig: (cfg) => ipcRenderer.invoke('cfg:save', cfg),
  testSsh: () => ipcRenderer.invoke('ssh:test'),
  getStatus: () => ipcRenderer.invoke('status:get'),
  gatewayStatus: () => ipcRenderer.invoke('gateway:status'),
  gatewayUsage: () => ipcRenderer.invoke('gateway:usage'),
  runDiag: () => ipcRenderer.invoke('diag:run'),
  getLogs: (source) => ipcRenderer.invoke('logs:get', source),
  svc: (unit, action) => ipcRenderer.invoke('svc:action', { unit, action }),
  getQr: () => ipcRenderer.invoke('qr:get'),
  regenerateQr: () => ipcRenderer.invoke('qr:regenerate'),
  quickMode: () => ipcRenderer.invoke('login:quickmode'),
  getModelConfig: () => ipcRenderer.invoke('model:getConfig'),
  saveModelConfig: (cfg) => ipcRenderer.invoke('model:saveConfig', cfg),
  testModel: (m) => ipcRenderer.invoke('model:test', m),
  fetchModels: (m) => ipcRenderer.invoke('model:fetchList', m),
  getBalances: () => ipcRenderer.invoke('model:balance'),
  panelInfo: () => ipcRenderer.invoke('panel:info'),
  panelOpen: () => ipcRenderer.invoke('panel:open'),
  panelCopy: (t) => ipcRenderer.invoke('panel:copy', t),
  runBackup: () => ipcRenderer.invoke('backup:run'),
  listBackups: () => ipcRenderer.invoke('backup:list'),
  listRemoteBackups: () => ipcRenderer.invoke('backup:remoteList'),
  downloadRemoteBackup: (name) => ipcRenderer.invoke('backup:download', name),
  openDir: (p) => ipcRenderer.invoke('shell:openDir', p),
  openPath: (p) => ipcRenderer.invoke('shell:openPath', p),
  openUrl: (u) => ipcRenderer.invoke('shell:openUrl', u),
});
